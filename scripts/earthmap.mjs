// Draws Earth's land (Natural Earth's 1:50m land outlines, public domain, via the world-atlas package) into a
// 1024 × 512 longitude × latitude mask and writes it, run-length packed, into js/space/EarthLand.js, which the
// terrain reads to give the Earth world its real continents. Run after changing the map: node scripts/earthmap.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { feature } from 'topojson-client';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const W = 1024, H = 512, SUB = 3; // (3 × 3 samples a pixel, so thin islands and straits survive)
const topo = JSON.parse(await readFile(`${ROOT}node_modules/world-atlas/land-50m.json`, 'utf8'));
const land = feature(topo, topo.objects.land);
const polygons = land.features.flatMap((f) => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates));
/** A ring with its longitudes made continuous (a ring that crosses 180° runs on past it instead of jumping back). */
const unwrap = (ring) => {
  let shift = 0;
  return ring.map(([x, y], i) => {
    if (i) { const dx = x + shift - ring[i - 1][0] - (ring[i - 1].shift ?? 0); if (dx > 180) shift -= 360; else if (dx < -180) shift += 360; }
    ring[i].shift = shift;
    return [x + shift, y];
  });
};
const shapes = polygons.map((rings) => rings.map(unwrap));

// even-odd fill, one polygon and one scanline (latitude) at a time; columns wrap round at 180°
const cover = new Float32Array(W * H), cols = W * SUB;
for (const rings of shapes) {
  for (let row = 0; row < H * SUB; row++) {
    const lat = 90 - ((row + 0.5) / (H * SUB)) * 180, xs = [];
    for (const ring of rings) {
      for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
        const [x1, y1] = ring[j], [x2, y2] = ring[i];
        if ((y1 > lat) !== (y2 > lat)) xs.push(x1 + ((lat - y1) / (y2 - y1)) * (x2 - x1));
      }
    }
    if (!xs.length) continue;
    xs.sort((a, b) => a - b);
    const y = Math.floor(row / SUB);
    for (let k = 0; k + 1 < xs.length; k += 2) {
      const a = ((xs[k] + 180) / 360) * cols, b = ((xs[k + 1] + 180) / 360) * cols;
      for (let c = Math.ceil(a - 0.5); c < b - 0.5; c++) cover[y * W + Math.floor((((c % cols) + cols) % cols) / SUB)] += 1 / (SUB * SUB);
    }
  }
}
// pack: a bit per pixel (land if at least half covered), then runs of alike bits as varints, base64
const bits = Array.from(cover, (v) => (v >= 0.5 ? 1 : 0));
const runs = [];
let cur = 0, n = 0;
for (const b of bits) {
  if (b === cur) { n++; continue; }
  runs.push(n);
  cur = b;
  n = 1;
}
runs.push(n);
const bytes = [];
for (let r of runs) {
  do { bytes.push((r & 127) | (r > 127 ? 128 : 0)); r >>>= 7; } while (r);
}
const b64 = Buffer.from(bytes).toString('base64');
const landShare = bits.reduce((s, b, i) => s + b * Math.cos(((Math.floor(i / W) + 0.5) / H - 0.5) * Math.PI), 0)
  / bits.reduce((s, _, i) => s + Math.cos(((Math.floor(i / W) + 0.5) / H - 0.5) * Math.PI), 0);
await writeFile(`${ROOT}js/space/EarthLand.js`, `// Generated by scripts/earthmap.mjs from Natural Earth's 1:50m land outlines (public domain). Don't edit by hand.
// Earth's land as a ${W} × ${H} mask: row 0 is the north pole edge, column 0 is 180°W; runs of sea and land alternate,
// starting with sea, each a little-endian base-128 number.
export const EARTH_LAND = { w: ${W}, h: ${H}, runs: '${b64}' };
`);
console.log(`js/space/EarthLand.js: ${runs.length} runs, ${b64.length} characters, land ${(landShare * 100).toFixed(1)}% of the surface`);
