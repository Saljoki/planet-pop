// Lists every file the game needs into precache.js, with a version hash of their contents. The service worker
// caches exactly these, and a new version replaces the old cache. Run after changing any game file:
//   npm run precache        (the test suite checks it's up to date)
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const DIRS = ['css', 'js', 'vendor', 'fonts', 'icons'];
const TOP = ['index.html', 'manifest.webmanifest'];
const SKIP = /(^|\/)(LICENSE|\.DS_Store)$/;

async function walk(dir) {
  const out = [];
  for (const e of await readdir(join(ROOT, dir), { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...await walk(p));
    else out.push(p.split(sep).join('/'));
  }
  return out;
}

export async function precacheSource() {
  const files = [...TOP, ...(await Promise.all(DIRS.map(walk))).flat()].filter((f) => !SKIP.test(f)).sort();
  const hash = createHash('sha256');
  for (const f of files) hash.update(f).update(await readFile(join(ROOT, f)));
  const version = hash.digest('hex').slice(0, 12);
  return `// Generated by scripts/precache.mjs: every file the game needs, and a version for the cache. Don't edit by hand.
self.PRECACHE = {
  version: '${version}',
  files: ${JSON.stringify(['./', ...files], null, 2).replace(/\n/g, '\n  ')},
};
`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeFile(join(ROOT, 'precache.js'), await precacheSource());
  console.log('precache.js written');
}
